-- Finalized MVP rules: permanent evaluations, temporary links, snapshots, and archives.
alter table public.evaluation_sessions
  add column if not exists form_id bigint,
  add column if not exists form_name text,
  add column if not exists client_position text,
  add column if not exists client_responses jsonb not null default '{}'::jsonb,
  add column if not exists archived_at timestamptz;

create table if not exists public.evaluation_forms (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  fields jsonb not null default '[]'::jsonb,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  archived_at timestamptz
);

create table if not exists public.evaluation_links (
  id bigint generated by default as identity primary key,
  evaluation_id bigint not null references public.evaluation_sessions(id) on delete restrict,
  token text not null unique,
  expires_at timestamptz,
  max_submissions integer not null default 1 check (max_submissions > 0),
  submission_count integer not null default 0 check (submission_count >= 0),
  submitted_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  archived_at timestamptz
);

alter table public.evaluation_sessions enable row level security;
alter table public.evaluation_forms enable row level security;
alter table public.evaluation_links enable row level security;

grant select, insert, update on public.evaluation_forms to authenticated;
grant select, insert, update on public.evaluation_links to authenticated;
grant select, update on public.evaluation_links to anon;

drop policy if exists "forms_authenticated_all" on public.evaluation_forms;
create policy "forms_authenticated_all" on public.evaluation_forms for all to authenticated using (true) with check (true);
drop policy if exists "links_authenticated_all" on public.evaluation_links;
create policy "links_authenticated_all" on public.evaluation_links for all to authenticated using (true) with check (true);
drop policy if exists "links_public_read_active" on public.evaluation_links;
create policy "links_public_read_active" on public.evaluation_links for select to anon using (archived_at is null and (expires_at is null or expires_at > now()) and submission_count < max_submissions and submitted_at is null);
drop policy if exists "links_public_submit_once" on public.evaluation_links;
create policy "links_public_submit_once" on public.evaluation_links for update to anon using (archived_at is null and submission_count < max_submissions and submitted_at is null) with check (submission_count <= max_submissions);

create index if not exists evaluation_links_evaluation_idx on public.evaluation_links(evaluation_id);
create index if not exists evaluation_links_status_idx on public.evaluation_links(expires_at, submission_count, submitted_at);
create index if not exists evaluation_sessions_archive_idx on public.evaluation_sessions(archived_at);
create unique index if not exists evaluation_sessions_active_cycle_idx on public.evaluation_sessions(employee_id, form_id, period)
  where archived_at is null and status not in ('rejected', 'archived');

